// Пункт 5.3.7: аварийный выход, когда прокси принят, но страница не грузится.
//
// Зачем отдельный модуль, а не десяток строк в proxy.rs. Логика сторожа не пересекается
// с чтением настроек и передачей аргументов движку ни одной строкой, а proxy.rs уже
// подошёл к тому размеру, после которого файл перестают читать целиком. Ровно по этой
// причине на 5.3.6 диагностика уехала из TauriBridge.ts в отдельный файл.
//
// Что закрывается. Страховка части четвёртой (probe в proxy.rs) ловит только грубые
// случаи: опечатку в порте и выключенный клиент прокси. Прокси, который ПРИНИМАЕТ
// соединение, но наружу не выпускает, проходит TCP-щуп, получает Applied — и окно
// остаётся со страницей ошибки движка. Панель настроек живёт ВНУТРИ этой страницы,
// поэтому выключить прокси человеку опять нечем: дефект 5.3.4 с другой причиной.
//
// Признак беды выбран прикладной, а не сетевой: выполнился ли наш код на живой странице
// AniList. Разбирать сетевые события движка со стороны Rust дороже и ненадёжнее, а
// отметка отвечает ровно на нужный вопрос и приходит из единственного места.
//
// Чего сторож НЕ умеет. Отличить мёртвый прокси от очень медленной, но живой сети.
// Поэтому вопрос задан предположением, а отказ не меняет ничего: настройка остаётся
// включённой, и следующий запуск пройдёт тем же путём.

use std::sync::atomic::{AtomicBool, Ordering};
use std::time::Duration;

use tauri::{AppHandle, Manager, State};
use tauri_plugin_dialog::{DialogExt, MessageDialogButtons, MessageDialogKind};
use tauri_plugin_store::StoreExt;

use crate::proxy::{self, ProxyOutcome};

/// Файл настроек и ключ тумблера. Повторяют proxy.rs, а тот — src/core/proxy.ts:
/// доступа к чужим модулям ни одна из сторон не имеет, а разойтись они не должны.
const STORE_FILE: &str = "animori-settings.json";
const KEY_ENABLED: &str = "set_proxy_on";

/// Сколько ждём признака жизни.
///
/// Двенадцать секунд — верх разумного. Через мёртвый прокси AniList не загрузится
/// вовсе, сколько ни жди, а живой, но медленный канал за это время успевает отдать
/// документ даже на слабой машине. Меньше — пойдут ложные срабатывания у тех, чей
/// прокси стоит в другой стране.
const PAGE_READY_TIMEOUT_MS: u64 = 12_000;

/// Отметка «страница ожила».
///
/// Отдельное состояние, а не поле ProxyState: команда ниже вызывается ВСЕГДА, в том
/// числе когда прокси выключен и сторож не заводится. Не окажись состояния — вызов
/// из страницы отвалился бы ошибкой, а в журнале появился бы отказ на пустом месте.
pub struct PageReady(AtomicBool);

/// Страница сообщает, что ожила.
///
/// НЕДОВЕРЕННЫЙ ВЫЗОВ, и это зафиксировано здесь намеренно. Команда приходит из
/// контекста anilist.co, то есть выполнить её может любой скрипт чужого сайта, а не
/// только наш бандл. Допустимо ровно потому, что худшее последствие злоупотребления —
/// сторож промолчит и человек не получит предложения выключить прокси. Ничего, кроме
/// этого флага, команда не трогает, параметров не принимает и ответа не даёт.
#[tauri::command]
pub fn animori_page_ready(state: State<'_, PageReady>) {
    state.0.store(true, Ordering::Relaxed);
}

/// Заводит сторожа. Вызывается один раз, сразу после создания окна.
///
/// Отсчёт идёт ОТ СОЗДАНИЯ ОКНА, а не от завершения навигации, и это осторожный
/// вариант, а не небрежный: при мёртвом прокси навигация не завершится никогда, и
/// сторож, привязанный к её событию, промолчал бы ровно в том случае, ради которого
/// написан. Цена — несколько сотен миллисекунд запаса, они заложены в срок ожидания.
pub fn spawn(app: &AppHandle) {
    app.manage(PageReady(AtomicBool::new(false)));

    // Сторож имеет смысл только там, где прокси действительно отдан движку. При Off,
    // Invalid и Unreachable окно и так идёт напрямую: предлагать выключить прокси в
    // ответ на пустую страницу значило бы ставить заведомо ложный диагноз — виновата
    // сеть, сам сайт или что угодно ещё, но не прокси.
    let Some((outcome, server)) = proxy::current_status(app) else {
        log::warn!("Сторож страницы не заведён: состояние прокси недоступно");
        return;
    };

    if outcome != ProxyOutcome::Applied {
        return;
    }

    let app = app.clone();

    // Обычный поток, а не задача асинхронного рантайма: вся работа — это сон и затем
    // блокирующий диалог. blocking_show держит поток до ответа человека, а ответа
    // может не быть минутами, и занимать этим поток рантайма, на котором работают наши
    // сетевые запросы, незачем. На главном потоке такой вызов и вовсе повесил бы окно.
    std::thread::spawn(move || {
        std::thread::sleep(Duration::from_millis(PAGE_READY_TIMEOUT_MS));

        if app.state::<PageReady>().0.load(Ordering::Relaxed) {
            return;
        }

        let seconds = PAGE_READY_TIMEOUT_MS / 1000;
        log::warn!("Страница не подала признаков жизни за {seconds} с при прокси {server}");

        let approved = app
            .dialog()
            .message(format!(
                "AniList не загрузился за {seconds} секунд.\n\n\
                 Похоже, дело в прокси {server}: он принимает соединение, но трафик \
                 через него не проходит.\n\n\
                 Выключить прокси и перезапустить приложение?"
            ))
            .title("AniMori: страница не загрузилась")
            .kind(MessageDialogKind::Warning)
            .buttons(MessageDialogButtons::OkCancelCustom(
                "Выключить и перезапустить".to_string(),
                "Оставить как есть".to_string(),
            ))
            .blocking_show();

        if !approved {
            log::info!("Аварийное выключение прокси отклонено пользователем");
            return;
        }

        if let Err(err) = disable_proxy(&app) {
            log::error!("Не удалось выключить прокси: {err}");

            // Перезапуск здесь был бы вредом: настройка осталась прежней, и приложение
            // вернулось бы в то же состояние, только с потерянной сессией. Вместо этого
            // говорим, где лежит файл и что в нём поправить руками.
            app.dialog()
                .message(format!(
                    "Не удалось сохранить настройки: {err}\n\n\
                     Выключите прокси вручную: в файле \
                     %APPDATA%\\com.foulnike.animori\\animori-settings.json \
                     задайте \"set_proxy_on\": false."
                ))
                .title("AniMori: настройки не сохранены")
                .kind(MessageDialogKind::Error)
                .blocking_show();
            return;
        }

        log::info!("Прокси выключен по аварийному сценарию, перезапуск");
        app.restart();
    });
}

/// Гасит тумблер прокси в общем файле настроек.
///
/// Пишется РОВНО ОДИН ключ. Адрес, порт, логин и список исключений остаются нетронутыми:
/// человек их вводил, и стирать всё из-за одного неудачного запуска нельзя — включить
/// прокси обратно он должен одним переключателем, а не вводом заново.
///
/// save() обязателен, и его отказ обязан быть виден. Без записи на диск перезапуск
/// поднимет приложение с тем же прокси, и человек попадёт в тот же диалог по кругу —
/// это хуже исходной болезни.
fn disable_proxy(app: &AppHandle) -> Result<(), String> {
    let store = app.store(STORE_FILE).map_err(|e| e.to_string())?;
    store.set(KEY_ENABLED, false);
    store.save().map_err(|e| e.to_string())
}
