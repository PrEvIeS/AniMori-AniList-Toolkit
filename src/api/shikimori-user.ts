// Пункт 3.6 плана: транспорт пользовательских (приватных) эндпоинтов Shikimori.
//
// Зачем отдельный файл, а не ветка внутри api/shikimori.ts: там живёт публичный клиент
// карточек тайтлов. У него перебор зеркал, шлюз темпа на 60 запросов в минуту и своя
// трактовка 404 (тайтл удалён по РКН — ищем на .rip). Пользовательским спискам не нужно
// ничего из этого: они лежат ровно на том домене, где у пользователя сессия, 404 там
// означает «страниц больше нет», а свой темп задаёт сам сценарий переноса паузами
// 500/350 мс. Смешение двух наборов правил в одной функции дало бы либо перебор зеркал
// там, где он бессмыслен, либо общий шлюз на две несвязанные подсистемы.
//
// РИСК №2 из AUDITION.md решается здесь и только здесь. Маршрутизация по RM3 п.3.6:
//
//   браузер — обычный fetch. Списки, история и избранное закрыты настройками приватности
//   и отдаются по сессионной куке. Куки уходят сами, потому что запрос идёт на тот же
//   origin, на котором работает юзерскрипт. Поведение конца Этапа 2 сохранено буквально:
//   тот же fetch(url) без опций, те же коды ответа у вызывающего кода.
//
//   Tauri — Bridge.http с credentials: 'omit'. Запрос уходит из Rust, куки WebView он
//   не видит, и честно выполнить 'include' нельзя. Поэтому режим заявлен анонимным явно,
//   а не подменён молча: пользователь получит 401/403 на скрытом профиле и обязан увидеть
//   в журнале причину. Требование открытого профиля — это пункт 2.7, о нём предупреждает
//   окно переноса.
//
// В браузере window.location.origin остаётся источником адреса: юзерскрипт запускается на
// том домене, который выбрал пользователь, и подменять его на константу нельзя — сессия
// привязана к конкретному зеркалу. В Tauri origin у документа свой (адрес оболочки), там
// он бессмыслен, поэтому берётся первый домен из SHIKI_DOMAINS.

import { Bridge } from '@/bridge'
import { IS_SHIKI, SHIKI_DOMAINS } from '../core/constants'
import { Logger } from '../utils/logger'

/** Домен по умолчанию для сред без своего origin Shikimori. */
const DESKTOP_ORIGIN = 'https://' + (SHIKI_DOMAINS[0] ?? 'shikimori.io')

/**
 * Таймаут одного запроса в десктопной среде. Списки тянутся страницами по 1000 записей,
 * поэтому потолок заметно выше зеркального (5000 мс в fetchShiki): там запрос дешёвый и
 * есть куда уйти, здесь уходить некуда, а обрыв на середине означает неполный перенос.
 */
const DESKTOP_TIMEOUT_MS = 20000

/** Предупреждение об анонимном доступе показывается один раз за сессию. */
let anonymousNoticeShown = false

/**
 * Уходят ли запросы без куки сессии.
 *
 * Проверяется платформа моста, а не наличие window: в WebView объект window существует,
 * но сессии Shikimori в нём нет.
 */
export function isAnonymousShikiAccess(): boolean {
  return Bridge.platform !== 'userscript'
}

/** Адрес, к которому приписываются пути вида `/api/users/1`. */
export function shikiUserOrigin(): string {
  if (Bridge.platform === 'userscript' && IS_SHIKI) return window.location.origin
  return DESKTOP_ORIGIN
}

/**
 * Текст отказа в доступе. В десктопе причина другая, чем в браузере, и одинаковое
 * «Профиль скрыт.» отправило бы пользователя проверять настройки приватности там, где
 * дело в анонимном транспорте.
 */
export function hiddenProfileMessage(): string {
  return isAnonymousShikiAccess()
    ? 'Профиль скрыт либо недоступен анонимно. В десктопной версии списки читаются без ' +
        'входа в аккаунт, поэтому профиль Shikimori должен быть открыт (публичен).'
    : 'Профиль скрыт.'
}

export interface ShikiUserResponse<T> {
  /** HTTP-код ответа. Разбирается вызывающим кодом: 404, 403, 429 значат разное. */
  status: number
  /** true для 200-299, как у fetch. */
  ok: boolean
  /** Разобранный JSON либо null: тело пустое, не разобралось или ответ не успешен. */
  data: T | null
}

/**
 * GET к пользовательскому эндпоинту Shikimori.
 *
 * Код вне 2xx исключением НЕ считается — по той же причине, что и в мосте: вызывающий
 * код различает 404 («страниц больше нет»), 403/401 («профиль закрыт») и 429 («подожди»),
 * и превращение их в ошибку стёрло бы разницу. Отклонение промиса означает только
 * транспортный сбой: TypeError от fetch в браузере, BridgeHttpError в десктопе.
 *
 * @param path Путь, начинающийся со слэша. Домен подставляется сам.
 */
export async function shikiUserGet<T>(path: string): Promise<ShikiUserResponse<T>> {
  const url = shikiUserOrigin() + path

  let status: number
  let ok: boolean
  let text: string

  if (isAnonymousShikiAccess()) {
    if (!anonymousNoticeShown) {
      anonymousNoticeShown = true
      Logger(
        'WARN',
        'Shikimori: запросы к спискам уходят анонимно, куки сессии недоступны. ' +
          'Профиль должен быть открыт, иначе сервер ответит отказом.',
      )
    }

    const res = await Bridge.http.request({
      method: 'GET',
      url,
      headers: { Accept: 'application/json' },
      credentials: 'omit',
      timeoutMs: DESKTOP_TIMEOUT_MS,
    })
    status = res.status
    ok = res.ok
    text = res.text
  } else {
    // Без опций намеренно: ровно так этот запрос выглядел в 1.9.1 и в конце Этапа 2.
    // Дефолтный credentials: 'same-origin' отправляет куки, потому что адрес свой.
    const res = await fetch(url)
    status = res.status
    ok = res.ok
    text = await res.text()
  }

  if (!ok) return { status, ok, data: null }

  try {
    return { status, ok, data: JSON.parse(text) as T }
  } catch (e) {
    // Раньше это была ошибка res.json() внутри общего try сценария переноса, и весь
    // перенос обрывался. Теперь битое тело равнозначно пустому ответу.
    Logger('ERROR', `Shikimori: не удалось разобрать ответ ${path}`, e)
    return { status, ok, data: null }
  }
}
