// Пункт 3.6 плана: транспорт пользовательских (приватных) эндпоинтов Shikimori.
// Пункт 3.7: точка входа переноса переехала на AniList, и это изменило маршрутизацию.
//
// Зачем отдельный файл, а не ветка внутри api/shikimori.ts: там живёт публичный клиент
// карточек тайтлов. У него перебор зеркал ради обхода блокировок, шлюз темпа на 60
// запросов в минуту и своя трактовка 404 (тайтл удалён по РКН — ищем на .rip).
// Пользовательским спискам общий шлюз не нужен: 404 у них значит «страниц больше нет»,
// а темп задаёт сам сценарий переноса паузами 500/350 мс. Смешение двух наборов правил
// в одной функции дало бы либо чужой троттлинг, либо неверную трактовку кодов.
//
// РИСК №2 из AUDITION.md решается здесь и только здесь.
//
// Почему обычного fetch тут больше нет. До 3.7 окно переноса рисовалось на Shikimori,
// запрос уходил на свой же origin и сессионная кука уезжала сама. Теперь и в браузере,
// и в десктопе перенос запускается со страницы anilist.co, а туда shikimori.io —
// чужой домен: голый fetch упрётся в CORS ещё до того, как сервер увидит куку.
// Поэтому оба пути идут через мост, и различаются они ровно одним полем:
//
//   юзерскрипт — credentials: 'include'. GM_xmlhttpRequest выполняет запрос вне правил
//   страницы и подставляет куки браузера для домена назначения, то есть сессию
//   Shikimori. Скрытый профиль в браузере читается как и раньше, из другой вкладки это
//   ничего не меняет. Домены уже перечислены в @connect шапки, расширять её не нужно.
//
//   Tauri — credentials: 'omit'. Запрос уходит из Rust, куки WebView он не видит, и
//   честно выполнить 'include' нельзя. Режим заявлен анонимным явно, а не подменён
//   молча: пользователь получит 401/403 на скрытом профиле и обязан увидеть в журнале
//   причину. Требование открытого профиля — пункт 2.7, о нём предупреждает окно переноса.
//
// Домен берётся из SHIKI_DOMAINS, а не из window.location: со страницы AniList своего
// origin Shikimori просто нет. Зеркала перебираются только при транспортном сбое —
// коды ответа возвращаются как есть, потому что 404 и 403 здесь осмысленны.

import { Bridge } from '@/bridge'
import { SHIKI_DOMAINS } from '../core/constants'
import { Logger } from '../utils/logger'

/**
 * Таймаут одного запроса. Списки тянутся страницами по 1000 записей, поэтому потолок
 * заметно выше зеркального (5000 мс в fetchShiki): там запрос дешёвый и есть куда уйти,
 * здесь уходить некуда, а обрыв на середине означает неполный перенос.
 */
const TIMEOUT_MS = 20000

/** Предупреждение об анонимном доступе показывается один раз за сессию. */
let anonymousNoticeShown = false

/**
 * Уходят ли запросы без куки сессии.
 *
 * Проверяется платформа моста, а не наличие window: в WebView объект window существует,
 * но сессии Shikimori в нём нет.
 */
export function isAnonymousShikiAccess(): boolean {
  return Bridge.platform !== 'userscript'
}

/**
 * Текст отказа в доступе. В десктопе причина другая, чем в браузере, и одинаковое
 * «Профиль скрыт.» отправило бы пользователя проверять настройки приватности там, где
 * дело в анонимном транспорте.
 */
export function hiddenProfileMessage(): string {
  return isAnonymousShikiAccess()
    ? 'Профиль скрыт либо недоступен анонимно. В десктопной версии списки читаются без ' +
        'входа в аккаунт, поэтому профиль Shikimori должен быть открыт (публичен).'
    : 'Профиль скрыт.'
}

export interface ShikiUserResponse<T> {
  /** HTTP-код ответа. Разбирается вызывающим кодом: 404, 403, 429 значат разное. */
  status: number
  /** true для 200-299, как у fetch. */
  ok: boolean
  /** Разобранный JSON либо null: тело пустое, не разобралось или ответ не успешен. */
  data: T | null
}

/**
 * GET к пользовательскому эндпоинту Shikimori.
 *
 * Код вне 2xx исключением НЕ считается — по той же причине, что и в мосте: вызывающий
 * код различает 404 («страниц больше нет»), 403/401 («профиль закрыт») и 429 («подожди»),
 * и превращение их в ошибку стёрло бы разницу. Отклонение промиса означает только
 * транспортный сбой, причём на всех зеркалах сразу.
 *
 * @param path Путь, начинающийся со слэша. Домен подставляется сам.
 */
export async function shikiUserGet<T>(path: string): Promise<ShikiUserResponse<T>> {
  const anonymous = isAnonymousShikiAccess()

  if (anonymous && !anonymousNoticeShown) {
    anonymousNoticeShown = true
    Logger(
      'WARN',
      'Shikimori: запросы к спискам уходят анонимно, куки сессии недоступны. ' +
        'Профиль должен быть открыт, иначе сервер ответит отказом.',
    )
  }

  const credentials: 'include' | 'omit' = anonymous ? 'omit' : 'include'
  let lastError: unknown = null

  for (const domain of SHIKI_DOMAINS) {
    const url = 'https://' + domain + path

    let status: number
    let ok: boolean
    let text: string

    try {
      const res = await Bridge.http.request({
        method: 'GET',
        url,
        headers: { Accept: 'application/json' },
        credentials,
        timeoutMs: TIMEOUT_MS,
      })
      status = res.status
      ok = res.ok
      text = res.text
    } catch (e) {
      // Сюда попадает только транспорт: сеть, таймаут, отмена. Пробуем следующее
      // зеркало — на нём может не быть блокировки провайдера. Куки у зеркал разные,
      // поэтому смена домена способна дать 403 вместо данных, и это честнее обрыва.
      lastError = e
      Logger('WARN', 'Shikimori: домен ' + domain + ' не ответил, пробую следующее зеркало', e)
      continue
    }

    if (!ok) return { status, ok, data: null }

    try {
      return { status, ok, data: JSON.parse(text) as T }
    } catch (e) {
      // Раньше это была ошибка res.json() внутри общего try сценария переноса, и весь
      // перенос обрывался. Теперь битое тело равнозначно пустому ответу.
      Logger('ERROR', 'Shikimori: не удалось разобрать ответ ' + path, e)
      return { status, ok, data: null }
    }
  }

  throw lastError instanceof Error
    ? lastError
    : new Error('Shikimori: ни одно зеркало не ответило.')
}
