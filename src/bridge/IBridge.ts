// ==== shell ====

/**
 * Операции над самим окном приложения.
 *
 * Пункт 4.3: подсистема появилась не по плану, а по факту первого живого запуска
 * десктопной сборки. В браузере перезагрузка бесплатна: есть F5, кнопка в тулбаре
 * и работающий location.reload(). В окне Tauri, открытом на внешнем URL, нет ни
 * тулбара, ни акселераторов, а страницу перезагружает бэкенд (WebviewWindow::reload).
 * Поэтому перезагрузка перестала быть деталью вёрстки и стала частью контракта
 * платформы — как и любое другое расхождение сред.
 *
 * Границу подсистемы держим узкой: сюда идёт только то, что WebView не умеет сам
 * или что в десктопе отказывает без участия оболочки. Ничего похожего на «свернуть»,
 * «закрыть», «полный экран» здесь нет, пока это не потребуется интерфейсу.
 */
export interface IShell {
  /**
   * Перезагружает текущую страницу.
   *
   * Промис разрешается ПОСЛЕ отправки команды, а не после загрузки документа:
   * в браузере вызывающий код к этому моменту уже уничтожен вместе со страницей.
   * Полагаться на код после await нельзя ни на одной платформе.
   *
   * Следствие, выяснившееся на 4.5: всё, что обязано успеть до гибели страницы,
   * нужно дожидаться ДО вызова — см. IStorage.flush() и reloadPage() в features/ui/reload.ts.
   */
  reload(): Promise<void>
  /**
   * Открывает внешний адрес там, где ему место: в браузере пользователя.
   *
   * Пункт 4.5, вторая причина расширения подсистемы. В браузере ссылку наружу
   * открывает сама вкладка — target="_blank" и window.open() работают без участия
   * кода. В WebView2 и то и другое превращается в запрос создать новое окно, и без
   * обработчика на стороне оболочки запрос отбрасывается МОЛЧА: ни новой вкладки,
   * ни ошибки, ни события. Именно так «умирали» ссылка «здесь» и ссылка авторизации
   * во вкладке «Аккаунт».
   *
   * Контракт: принимаются только адреса со схемой http или https. Реализация в Tauri
   * дополнительно проверяет схему на стороне Rust — вызов приходит из контекста
   * anilist.co, то есть из недоверенного кода, и разрешать оттуда произвольные схемы
   * значит разрешать запуск произвольных программ на машине пользователя.
   *
   * Внутренние переходы (anilist.co) сюда НЕ идут: они должны оставаться в окне и
   * обрабатываться маршрутизацией самого сайта.
   */
  openExternal(url: string): Promise<void>
  /**
   * Шаг назад по истории просмотра.
   *
   * Пункт 4.5, третья причина расширения. В браузере шаги по истории дают кнопки
   * тулбара, Alt+←/→ и боковые клавиши мыши. В окне оболочки ничего из этого нет,
   * поэтому навигацию рисует сам интерфейс, а способ выполнить шаг живёт здесь.
   *
   * Сегодня обе реализации сводятся к history.back(), и это нормально: метод в контракте
   * нужен не ради разных реализаций сейчас, а ради единственного места, куда придётся
   * лезть, если WebView2 потребует шаг со стороны Rust — ровно так, как это уже
   * случилось с перезагрузкой. Прикладной код не должен знать разницу.
   *
   * Если идти некуда, вызов ничего не делает и не считается ошибкой: история — не
   * чтение, её глубину браузер не разглашает, и заранее узнать о границе нельзя.
   */
  back(): Promise<void>
  /** Шаг вперёд по истории просмотра. Всё сказанное про back() верно и здесь. */
  forward(): Promise<void>
}

