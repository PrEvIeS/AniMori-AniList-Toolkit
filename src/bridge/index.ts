// Пункт 3.4 плана: единственная точка входа к мосту для прикладного кода.
//
// Код вне src/bridge импортирует только '@/bridge'. Импортировать MonkeyBridge или
// TauriBridge напрямую нельзя: во втором случае в бандл юзерскрипта уедут пакеты
// @tauri-apps/*, неработоспособные в браузере (РИСК, введённый на пункте 3.3).
//
// Выбор реализации сделан на этапе сборки, а не в рантайме. Схема «импортировать оба
// моста и ветвиться по __ANIMORI_PLATFORM__» отвергнута: TauriBridge создаёт LazyStore
// на верхнем уровне модуля, а такой побочный эффект Rollup вправе сохранить даже после
// удаления недостижимой ветки — вместе с ним приехали бы и сами пакеты. Вместо этого
// resolve.alias в vite.config.ts разрешает псевдопуть '@bridge-impl' в один конкретный
// файл, и вторая реализация просто не попадает в граф модулей.
//
// tsconfig.json указывает '@bridge-impl' на MonkeyBridge: тайпчекеру нужна одна
// определённая цель. На проверку это не влияет — обе реализации объявлены как IBridge,
// а TauriBridge входит в include и проверяется сам по себе.

