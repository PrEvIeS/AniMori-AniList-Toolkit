// Пункт 5.3 плана: прокси. ТОЛЬКО десктоп.
//
// Почему это отдельный модуль, а не поля в AniMoriSettings (core/settings.ts):
//
//   1. Модуль ЧИСТЫЙ — здесь нет ни одного импорта. Только поэтому его вправе
//      импортировать и прикладной код, и сам мост (src/bridge/TauriBridge.ts).
//      Положить эти ключи в core/settings.ts было нельзя: тот модуль импортирует
//      '@/bridge', и обратный импорт замкнул бы цикл ровно того же вида, из-за
//      которого в settings.ts нет логгера.
//
//   2. Прокси не применяется на ходу. Канал WebView2 задаётся аргументом командной
//      строки процессу при запуске, то есть смена адреса требует перезапуска
//      приложения. Держать такой ключ в одном ряду с тумблерами, которые действуют
//      по клику, — обманывать пользователя.
//
//   3. В юзерскрипте потребителя нет вовсе: там маршрут запроса выбирает браузер,
//      и никакая настройка страницы на это не влияет. Панель настроек показывает
//      раздел только в сборке tauri.
//
// Имена ключей хранилища перечислены здесь и больше нигде не повторяются: их читают
// и мост, и панель настроек, и разойтись они не должны.

export type ProxyKind = 'http' | 'socks5'

export interface ProxyConfig {
  enabled: boolean
  kind: ProxyKind
  host: string
  port: number
  login: string
  /**
   * Пароль хранится В ОТКРЫТОМ ВИДЕ в animori-settings.json рядом с остальными
   * настройками. Это осознанный выбор, а не недоделка: единственная альтернатива —
   * системное хранилище секретов, а это ещё один плагин, ещё одно разрешение в
   * capabilities и отдельный путь отказа на машине без такого хранилища. Панель
   * настроек обязана предупредить об этом прямым текстом.
   */
  password: string
  /**
   * Адреса, которые идут напрямую, минуя прокси. Ввод свободный: разделителем
   * считаются запятая, точка с запятой и перевод строки — люди пишут списки
   * по-разному, и придираться к разделителю здесь незачем.
   */
  bypass: string
}

/** Ключи хранилища. Единственное место, где они объявлены. */
export const PROXY_KEYS = {
  enabled: 'set_proxy_on',
  kind: 'set_proxy_kind',
  host: 'set_proxy_host',
  port: 'set_proxy_port',
  login: 'set_proxy_login',
  password: 'set_proxy_pass',
  bypass: 'set_proxy_bypass',
} as const

/**
 * Значения на случай отсутствия ключа.
 *
 * Выключено по умолчанию: прокси — инструмент для того, кому он нужен, и включённый
 * без спроса он превратил бы рабочее приложение в неработающее.
 *
 * Порт 8080 — самый частый для HTTP-прокси; для socks5 пользователь обычно правит его
 * на 1080. Подставлять разные значения по типу мы не будем: настройка, которая молча
 * меняется от переключения соседней, ведёт себя непредсказуемо для человека.
 *
 * Локальные адреса в списке исключений с самого начала: гонять петлю через внешний
 * прокси не нужно никогда, а забыть про неё легко.
 */
export const DEFAULT_PROXY: ProxyConfig = {
  enabled: false,
  kind: 'http',
  host: '',
  port: 8080,
  login: '',
  password: '',
  bypass: 'localhost, 127.0.0.1',
}

/**
 * Приводит прочитанное из хранилища к известному типу.
 *
 * В файле настроек может лежать что угодно: он правится руками, переживает смену
 * версий и не имеет схемы. Неизвестное значение трактуется как http, а не как ошибка:
 * отказаться работать из-за испорченной строки хуже, чем взять самый частый вариант.
 */
export function normalizeProxyKind(value: unknown): ProxyKind {
  return value === 'socks5' ? 'socks5' : 'http'
}

/**
 * Порт как целое в допустимом диапазоне. Ноль означает «значения нет»: это единственный
 * способ отличить непригодный ввод от осмысленного, не бросая исключение в мосте.
 *
 * Строка тоже принимается: поле ввода в панели настроек отдаёт именно строку, и
 * приводить её на каждой стороне отдельно — верный путь к расхождению.
 */
export function normalizeProxyPort(value: unknown): number {
  const parsed = typeof value === 'number' ? value : Number.parseInt(String(value ?? ''), 10)
  if (!Number.isInteger(parsed) || parsed < 1 || parsed > 65535) return 0
  return parsed
}

/** Пригодна ли настройка к применению: включена, адрес задан, порт осмыслен. */
export function isProxyUsable(config: ProxyConfig): boolean {
  return config.enabled && config.host.trim().length > 0 && normalizeProxyPort(config.port) !== 0
}

/**
 * Адрес прокси одной строкой.
 *
 * Логин и пароль здесь СОЗНАТЕЛЬНО не подставляются, хотя схема это позволяет.
 * Причина простая: пароли содержат двоеточия, собаки и слеши, и склейка вида
 * user:pass@host ломается на первом же таком символе. Учётные данные уходят
 * отдельным полем — см. basicAuth в TauriBridge.
 */
export function proxyUrl(config: ProxyConfig): string | null {
  if (!isProxyUsable(config)) return null

  const scheme = config.kind === 'socks5' ? 'socks5' : 'http'
  return `${scheme}://${config.host.trim()}:${normalizeProxyPort(config.port)}`
}

/** Список исключений в виде отдельных записей, без пустых. */
export function proxyBypassList(config: ProxyConfig): string[] {
  return config.bypass
    .split(/[,;\n]+/)
    .map((item) => item.trim())
    .filter((item) => item.length > 0)
}
