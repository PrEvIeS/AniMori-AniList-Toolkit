// Итерация 5.2: точка входа тоста о недоступности источников.
//
// Сделано по образцу features/ui/settings.ts: модуль только монтирует компонент,
// вся логика показа живёт в NetToast.vue.
//
// Приложение НЕ постраничное (pageScoped не выставлен): тост живёт в body всю
// сеансию и обязан переживать переходы по сайту. Снятие на смене роута сбрасывало бы
// признак «уже показано» вместе с компонентом, и плашка вылезала бы заново на каждой
// странице — то есть ровно то, от чего его берегли однократным показом.
//
// Наблюдение за контейнером не нужно по той же причине, что и у модалок: корень в body,
// а React туда не залезает.

import { mountApp } from '../../utils/vue-mounter'
import NetToast from './NetToast.vue'

export const NET_TOAST_APP_KEY = 'net-toast'

/**
 * Монтирует тост. Вызывать после loadSettings() и желательно до первых сетевых
 * запросов: компонент сверяется с уже накопленным учётом один раз при монтировании,
 * а дальше ждёт событий подписки.
 */
export function initNetToast(): void {
  mountApp(NET_TOAST_APP_KEY, NetToast, {
    container: document.body,
    watchContainer: false,
  })
}
