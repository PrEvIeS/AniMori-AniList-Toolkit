// Пункт 4.3 (внеплановая правка по итогам первого живого запуска оболочки):
// единая точка перезагрузки страницы плюс средства её вызвать в десктопной сборке.
//
// Предыстория. До этого в коде был ровно один способ перезагрузиться — location.reload()
// в подвале настроек. В браузере того хватало: есть ещё и F5, и кнопка тулбара.
// В окне WebView2, открытом на внешнем URL, нет ни тулбара, ни акселераторов, а сам
// location.reload() до навигации не доходит — перезагрузку выполняет только бэкенд
// оболочки. В итоге в десктопной сборке не работали ни «Применить и перезагрузить»,
// ни перезагрузка после очистки кэша, а обновить страницу вручную было нечем вообще.
//
// Почему не меню и не штатные акселераторы Tauri. Меню и глобальные горячие клавиши —
// это отдельные подсистемы со своими плагинами и разрешениями, и ради одной команды
// тянуть их нет смысла. Здесь всё решается тем же способом, как остальной интерфейс:
// кнопка в своей же панели и обработчик keydown в странице.

import { Bridge } from '@/bridge'
import { Logger } from '@/utils/logger'

import { ACTION_ORDER, registerActionButton } from './action-panel-state'

export const RELOAD_BUTTON_ID = 'am-reload-btn'

/** Круговая стрелка. Формат — как у TAB_ICONS: внутренности SVG 24×24 без тега svg. */
export const RELOAD_ICON =
  '<path d="M21 12a9 9 0 1 1-2.64-6.36"/><polyline points="21 3 21 9 15 9"/>'

/**
 * Перезагружает страницу через мост.
 *
 * Весь прикладной код обязан звать именно эту функцию, а не location.reload():
 * в десктопной сборке второе молча ничего не делает.
 *
 * Ошибка команды не вылетает наружу, а пишется в журнал: вызывающие места — это
 * обработчики клика в настройках, где делать с исключением нечего. Молчаливого catch
 * тут нет: без записи отказ выглядел бы ровно как сегодняшний дефект — кнопка нажата,
 * не происходит ничего, причина неизвестна.
 */
export async function reloadPage(): Promise<void> {
  try {
    await Bridge.shell.reload()
  } catch (e) {
    Logger('ERROR', 'Не удалось перезагрузить страницу', e)
  }
}

/** Повторный вызов initReloadControls() не должен вешать второй обработчик клавиатуры. */
let controlsInstalled = false

/**
 * Регистрирует средства перезагрузки: кнопку в панели действий и F5 / Ctrl+R.
 *
 * Только для десктопной сборки. В браузере и то, и другое уже есть у самого браузера,
 * а лишняя пилюля в панели там была бы чистым шумом — тумблера в настройках поэтому
 * тоже нет: видимость определяется платформой, а не вкусом.
 */
export function initReloadControls(): void {
  if (Bridge.platform !== 'tauri') return
  if (controlsInstalled) return
  controlsInstalled = true

  // Своего значения в ACTION_ORDER кнопка не получает осознанно: там перечислены
  // кнопки, общие для двух платформ и повторяющие раскладку монолита. Перезагрузка
  // становится левее шестерёнки, как и в тулбаре браузера.
  registerActionButton({
    id: RELOAD_BUTTON_ID,
    label: '↻',
    title: 'Обновить страницу (F5)',
    order: ACTION_ORDER.settings - 5,
    icon: RELOAD_ICON,
    onClick: () => {
      void reloadPage()
    },
  })

  window.addEventListener(
    'keydown',
    (e: KeyboardEvent) => {
      // Альтернативные раскладки с Shift и Alt не перехватываем: Ctrl+Shift+R в браузере
      // — жёсткая перезагрузка без кэша, а мы такого обещать не можем.
      if (e.altKey || e.shiftKey || e.metaKey) return

      const isF5 = e.key === 'F5' && !e.ctrlKey
      const isCtrlR = e.ctrlKey && (e.key === 'r' || e.key === 'R')
      if (!isF5 && !isCtrlR) return

      // В поле ввода Ctrl+R не перехватываем: потерять набранный отзыв или собственный
      // словарь из-за промаха по клавише неприятно. F5 в полях ничего не значит,
      // поэтому ограничение касается только сочетания с Ctrl.
      if (isCtrlR) {
        const el = document.activeElement as HTMLElement | null
        const tag = el?.tagName
        if (tag === 'INPUT' || tag === 'TEXTAREA' || tag === 'SELECT' || el?.isContentEditable) {
          return
        }
      }

      e.preventDefault()
      void reloadPage()
    },
    // capture: сайт может гасить события клавиатуры на своих узлах, а перезагрузка обязана
    // работать всегда — это единственный способ выйти из застрявшего состояния.
    { capture: true },
  )
}
